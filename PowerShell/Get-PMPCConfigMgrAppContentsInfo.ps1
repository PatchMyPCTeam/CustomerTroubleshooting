[CmdletBinding()]
param (
    [Parameter(Mandatory = $true, ParameterSetName = 'ByPackageId')]
    [string]
    $PackageId,
    [Parameter(Mandatory = $true, ParameterSetName = 'ByModelName')]
    [string]
    $ModelName,
    [Parameter(Mandatory = $true)]
    [string]
    $SmsProvider
)

$dllRoot = "$ENV:SMS_ADMIN_UI_PATH\..\..\bin\"
Add-Type -Path (Join-Path $dllRoot AdminUI.WqlQueryEngine.dll)
Add-Type -Path (Join-Path $dllRoot AdminUI.AppManFoundation.dll)
$connectionManager = [Microsoft.ConfigurationManagement.ManagementProvider.WqlQueryEngine.WqlConnectionManager]::new()
$null = $connectionManager.Connect($SmsProvider)
$SiteCode = $connectionManager.NamedValueDictionary['ConnectedSiteCode']

if ($PSCmdlet.ParameterSetName.Equals('ByPackageId')) {
    $ModelName = (Get-WmiObject -Namespace root\sms\site_$SiteCode -Query "SELECT ModelName FROM SMS_CIContentPackage WHERE PackageID='$PackageId'").ModelName
}

$AppQuery = "SELECT * FROM SMS_ApplicationLatest WHERE ModelName='$ModelName'"
[Microsoft.ConfigurationManagement.ApplicationManagement.NamedObject]::DefaultScope = [Microsoft.ConfigurationManagement.AdminConsole.AppManFoundation.ApplicationFactory]::GetAuthoringScope($connectionManager)
$WqlResultObject = [Microsoft.ConfigurationManagement.ManagementProvider.WqlQueryEngine.WqlResultObject]::new($connectionManager, [Microsoft.ConfigurationManagement.ManagementProvider.SmsNamedValuesDictionary]::new(), (Get-WmiObject -Namespace root\sms\site_$SiteCode -Query $AppQuery))
$WqlResultObject.Get()
$wrapped = [Microsoft.ConfigurationManagement.AdminConsole.AppManFoundation.AppManWrapper]::WrapExisting($WqlResultObject, [Microsoft.ConfigurationManagement.AdminConsole.AppManFoundation.ApplicationFactory]::new())
[Microsoft.ConfigurationManagement.ApplicationManagement.Application]$appObject = $wrapped.InnerAppManObject
$Installer = $appObject.DeploymentTypes.Installer
[pscustomobject]@{
    Purpose = 'Install Content'
    Id = $Installer.InstallContent.Id
    IsReadOnly = $Installer.InstallContent.IsReadOnly
    IsChanged = $Installer.InstallContent.IsChanged
}
[pscustomobject]@{
    Purpose = 'Uninstall Content'
    Id = $Installer.UninstallContent.Id
    IsReadOnly = $Installer.UninstallContent.IsReadOnly
    IsChanged = $Installer.UninstallContent.IsChanged
}
foreach($content in $Installer.Contents) {
    [pscustomobject]@{
        Purpose = 'All AllContent'
        Id = $content.Id
        IsReadOnly = $content.IsReadOnly
        IsChanged = $content.IsChanged
    }
}

